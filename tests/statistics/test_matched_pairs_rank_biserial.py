"""Hand-computed regression tests for the matched-pairs rank-biserial.

Every expected value below is derived from the definition
``rb = (W+ - W-) / (W+ + W-)`` with ranks worked out by hand (ties take the
mean of their positions, matching the Wilcoxon signed-rank ranking
convention). The expectations are not generated by the implementation; one
test additionally cross-checks the tie convention against scipy's
*one-sided* Wilcoxon statistic, which is a different quantity from the
two-sided minimum statistic that the audited defect was derived from.
"""

import pytest

from ai_eval_platform.statistics.effect_size import matched_pairs_rank_biserial


def test_all_positive_differences_give_plus_one():
    # |d| = [1, 2, 3] ranks [1, 2, 3]: W+ = 6, W- = 0, rb = 6/6.
    assert matched_pairs_rank_biserial([1.0, 2.0, 3.0]) == pytest.approx(1.0)


def test_all_negative_differences_give_minus_one():
    # |d| = [1, 2, 3] ranks [1, 2, 3]: W+ = 0, W- = 6, rb = -6/6.
    assert matched_pairs_rank_biserial([-1.0, -2.0, -3.0]) == pytest.approx(-1.0)


def test_mixed_sign_differences_with_dominant_positive_rank_sum():
    # d = [3, -1, 2]; |d| = [3, 1, 2] ranks [3, 1, 2].
    # W+ = 3 + 2 = 5, W- = 1, rb = (5 - 1) / 6 = 2/3.
    assert matched_pairs_rank_biserial([3.0, -1.0, 2.0]) == pytest.approx(2.0 / 3.0)


def test_mixed_sign_differences_with_dominant_negative_rank_sum():
    # d = [-3, 1, -2]; |d| = [3, 1, 2] ranks [3, 1, 2].
    # W+ = 1, W- = 3 + 2 = 5, rb = (1 - 5) / 6 = -2/3.
    assert matched_pairs_rank_biserial([-3.0, 1.0, -2.0]) == pytest.approx(-2.0 / 3.0)


def test_tied_absolute_differences_use_average_ranks():
    # |d| sorted = [1, 1, 2]; the tie over positions 1..2 shares rank 1.5,
    # and |d| = 2 takes rank 3.
    # W+ = 1.5 (d = +1) + 3 (d = +2) = 4.5; W- = 1.5 (d = -1);
    # rb = (4.5 - 1.5) / 6 = 0.5.
    assert matched_pairs_rank_biserial([1.0, -1.0, 2.0]) == pytest.approx(0.5)


def test_tied_absolute_differences_with_two_tie_clusters():
    # |d| sorted = [1, 1, 1, 2, 2]: positions 1..3 share rank 2, 4..5 share
    # rank 4.5.
    # W+ = 2 (d = +1) + 4.5 (d = +2) = 6.5
    # W- = 2 + 2 (d = -1 twice) + 4.5 (d = -2) = 8.5
    # rb = (6.5 - 8.5) / 15 = -2/15.
    assert matched_pairs_rank_biserial(
        [1.0, -1.0, 2.0, -1.0, -2.0]
    ) == pytest.approx(-2.0 / 15.0)


def test_zero_differences_are_discarded_before_ranking():
    # Zeros are dropped (wilcox zero method); |d| = [1, 2] ranks [1, 2].
    # W+ = 1 (d = +1), W- = 2 (d = -2), rb = (1 - 2) / 3 = -1/3.
    assert matched_pairs_rank_biserial([1.0, 0.0, -2.0, 0.0]) == pytest.approx(
        -1.0 / 3.0
    )


def test_all_zero_and_empty_inputs_have_no_defined_effect_size():
    # Zero denominator: no non-zero differences exist, so no effect size is
    # defined and None is returned rather than a fabricated 0.0.
    assert matched_pairs_rank_biserial([0.0, 0.0, 0.0]) is None
    assert matched_pairs_rank_biserial([]) is None


def test_result_is_invariant_to_difference_order():
    differences = [1.0, -3.0, 2.0, -0.5, 0.0]
    expected = matched_pairs_rank_biserial(differences)

    assert matched_pairs_rank_biserial(list(reversed(differences))) == expected
    assert matched_pairs_rank_biserial(sorted(differences)) == expected


def test_rank_convention_matches_scipy_one_sided_wilcoxon_statistic():
    # scipy's alternative="greater" statistic is W+ itself (verified against
    # the installed scipy 1.18.0); this pins the tie/zero ranking used here
    # to the convention scipy's wilcoxon applies internally.
    from scipy.stats import wilcoxon

    differences = [1.0, -1.0, 2.0, -1.0, -2.0]
    non_zero = [difference for difference in differences if difference != 0.0]
    w_plus = float(wilcoxon(non_zero, alternative="greater").statistic)

    assert w_plus == 6.5
    assert matched_pairs_rank_biserial(differences) == pytest.approx(
        (2.0 * w_plus - 15.0) / 15.0
    )


def test_rejects_non_finite_non_real_and_non_sequence_inputs():
    with pytest.raises(ValueError, match="finite"):
        matched_pairs_rank_biserial([1.0, float("inf")])
    with pytest.raises(TypeError, match="real numbers"):
        matched_pairs_rank_biserial([1.0, True])
    with pytest.raises(TypeError, match="list or tuple"):
        matched_pairs_rank_biserial("not-a-sequence")
